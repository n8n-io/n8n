import type { WriteBoundary } from './boundary.js';
import type { NodeSpec } from './types.js';

export function generateNodeCard(
	boundary: WriteBoundary,
	spec: NodeSpec,
	folderName: string,
): void {
	const ops = spec.resources
		.flatMap((r) =>
			r.operations.map((op) => `- **${r.name} → ${op.name}** (\`${op.method} ${op.path}\`)`),
		)
		.join('\n');

	const content = `# ${spec.displayName} node card

Plain-English summary for QA and non-engineers. Generated by \`node-scaffolder\`.

## What it does

${spec.description}

This is a **declarative REST** node: n8n sends HTTP requests based on the resource and operation you pick. It does not run custom JavaScript in \`execute()\`.

${spec.simulation ? '_Simulation / scaffold artifact — not an official n8n product node._' : ''}

## Inputs and outputs

| | |
|---|---|
| **Input** | Main (items from the previous node) |
| **Output** | Main (API response items) |
| **Base URL** | \`${spec.baseUrl}\` |
| **Auth** | \`${spec.auth}\`${spec.auth === 'none' ? '' : ' (credential draft only — not registered yet)'} |

## Operations scaffolded

${ops || '- (none)'}

## Auth / credentials

${
	spec.auth === 'none'
		? 'No credentials required for this scaffold.'
		: `A **credential draft** was written under \`credentials-draft/\` inside this folder.

It is **not** wired into n8n yet. To activate it someone must copy it to \`packages/nodes-base/credentials/\` and register it in \`package.json\` — those paths are **outside** this scaffolder's write boundary on purpose.`
}

## QA test-plan checklist

- [ ] Confirm files only exist under \`packages/nodes-base/nodes/${folderName}/\`
- [ ] Register the node in \`packages/nodes-base/package.json\` → \`"n8n"."nodes"\` (out of boundary)
- [ ] ${spec.auth === 'none' ? 'N/A — no credentials' : 'Copy credential draft to `credentials/` and register it (out of boundary)'}
- [ ] Rebuild / restart n8n and confirm **${spec.displayName}** appears in the node picker
- [ ] Run a valid **${spec.resources[0]?.name ?? 'Item'} → ${spec.resources[0]?.operations[0]?.name ?? 'Get Many'}** call against a test environment (or nock)
- [ ] Confirm invalid / missing auth shows a clear error (not a cryptic stack trace)
- [ ] Lint clean: \`cd packages/nodes-base && pnpm exec eslint "nodes/${folderName}/**/*.ts"\`
- [ ] Tests: \`cd packages/nodes-base && pnpm test nodes/${folderName}/test/${folderName}.test.ts\` (after registration + pinData/nock updates)

## Important policy note

Unsolicited **new node** PRs into the n8n monorepo are normally **auto-closed** (see \`CONTRIBUTING.md\`). For real custom nodes, prefer a [community node package](https://docs.n8n.io/integrations/creating-nodes/overview/) via \`npm create @n8n/node\`.
`;

	boundary.writeAllowed('NODE_CARD.md', content);
}
