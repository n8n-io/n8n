// Generates normalize_tables.zig and testdata/normalize_cases.txt from the
// Unicode normalization of the Node.js that runs it (ICU in V8), so the
// runtime's String.prototype.normalize gives the same results as JavaScript.
//
// JavaScript does not show the canonical combining classes, so the script
// derives them: a code point is a non-starter when it moves past U+0334
// (class 1) or U+0345 (class 240) in NFD, and two non-starters compare by
// the order that NFD gives them. The numbers are ranks, not the Unicode
// values; normalization uses only their order and zero.
//
// Run from workflow-runtime: node src/core/gen_normalize.mjs (it runs zig fmt on the output)
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const MAX = 0x10ffff;
const isSurrogate = (cp) => cp >= 0xd800 && cp <= 0xdfff;
const isHangul = (cp) => cp >= 0xac00 && cp <= 0xd7a3;
const cps = (s) => [...s].map((c) => c.codePointAt(0));
const ch = (cp) => String.fromCodePoint(cp);

// Full decompositions (Hangul syllables are algorithmic in the runtime).
const canonical = [];
const compat = [];
for (let cp = 0; cp <= MAX; cp++) {
	if (isSurrogate(cp) || isHangul(cp)) continue;
	const s = ch(cp);
	const d = cps(s.normalize('NFD'));
	const k = cps(s.normalize('NFKD'));
	const dSame = d.length === 1 && d[0] === cp;
	if (!dSame) canonical.push([cp, d]);
	if (!(k.length === d.length && k.every((x, i) => x === d[i]))) compat.push([cp, k]);
}

// Combining classes of the code points that normalized text holds.
const nonStarters = [];
for (let cp = 0; cp <= MAX; cp++) {
	if (isSurrogate(cp)) continue;
	const s = ch(cp);
	if (s.normalize('NFKD') !== s || s.normalize('NFD') !== s) continue;
	const moves = (a, b) => `a${a}${b}`.normalize('NFD') === `a${b}${a}`;
	if (moves(s, '̴') || moves('ͅ', s)) nonStarters.push(cp);
}
const cmp = (x, y) => {
	if (`a${ch(x)}${ch(y)}`.normalize('NFD') === `a${ch(y)}${ch(x)}`) return 1;
	if (`a${ch(y)}${ch(x)}`.normalize('NFD') === `a${ch(x)}${ch(y)}`) return -1;
	return 0;
};
const sorted = [...nonStarters].sort(cmp);
const ccc = new Map();
let rank = 1;
for (let i = 0; i < sorted.length; i++) {
	if (i > 0 && cmp(sorted[i - 1], sorted[i]) !== 0) rank++;
	ccc.set(sorted[i], rank);
}
if (rank > 255) throw new Error('too many classes');

// Primary composites as pairs: the NFC of all but the last code point of the
// decomposition is one code point, which composes with the last one.
const pairs = [];
for (const [cp, d] of canonical) {
	if (ch(cp).normalize('NFC') !== ch(cp) || d.length < 2) continue;
	const head = String.fromCodePoint(...d.slice(0, -1)).normalize('NFC');
	const h = cps(head);
	if (h.length !== 1) throw new Error(`no pair for ${cp.toString(16)}`);
	pairs.push([h[0], d[d.length - 1], cp]);
}
pairs.sort((a, b) => a[0] - b[0] || a[1] - b[1]);

// The Zig source.
const pool = [];
const entries = (list) =>
	list.map(([cp, d]) => {
		const start = pool.length;
		pool.push(...d);
		return `.{ .cp = 0x${cp.toString(16)}, .start = ${start}, .len = ${d.length} },`;
	});
const canonicalEntries = entries(canonical);
const compatEntries = entries(compat);
const lines = [
	'//! Generated by gen_normalize.mjs from the normalization of Node.js. Do not edit.',
	`//! ${canonical.length} canonical and ${compat.length} compatibility decompositions,`,
	`//! ${ccc.size} non-starters in ${rank} classes, ${pairs.length} composition pairs.`,
	'',
	'pub const Decomp = struct { cp: u21, start: u16, len: u8 };',
	'pub const Class = struct { cp: u21, class: u8 };',
	'pub const Pair = struct { a: u21, b: u21, c: u21 };',
	'',
	'/// Full canonical decompositions (NFD), sorted by code point.',
	'pub const canonical = [_]Decomp{',
	...canonicalEntries,
	'};',
	'',
	'/// Full compatibility decompositions (NFKD) where they differ from NFD, sorted.',
	'pub const compat = [_]Decomp{',
	...compatEntries,
	'};',
	'',
	'/// The code points of the decompositions.',
	'pub const pool = [_]u21{',
	...Array.from({ length: Math.ceil(pool.length / 12) }, (_, i) =>
		pool
			.slice(i * 12, i * 12 + 12)
			.map((x) => `0x${x.toString(16)},`)
			.join(' '),
	),
	'};',
	'',
	'/// Combining classes (ranks) of the non-starters, sorted by code point.',
	'pub const classes = [_]Class{',
	...[...ccc.entries()].sort((a, b) => a[0] - b[0]).map(([cp, c]) => `.{ .cp = 0x${cp.toString(16)}, .class = ${c} },`),
	'};',
	'',
	'/// Primary composites: `a` and `b` compose to `c`. Sorted by `a`, then `b`.',
	'pub const pairs = [_]Pair{',
	...pairs.map(([a, b, c]) => `.{ .a = 0x${a.toString(16)}, .b = 0x${b.toString(16)}, .c = 0x${c.toString(16)} },`),
	'};',
	'',
];
writeFileSync(join(here, 'normalize_tables.zig'), lines.join('\n'));
execFileSync('zig', ['fmt', join(here, 'normalize_tables.zig')]);

// Test cases: random strings over characters that normalization changes.
let seed = 20261112;
const rnd = (k) => {
	seed = (seed * 1103515245 + 12345) % 2147483648;
	return seed % k;
};
const interesting = [
	...canonical.map((c) => c[0]),
	...compat.map((c) => c[0]),
	...nonStarters,
	0xac00, 0xac01, 0xd7a3, 0x1100, 0x1161, 0x11a8, 0x1112, 0x1175, 0x11c2,
	0x61, 0x65, 0x6f, 0x75, 0x41, 0x20, 0x31, 0x3b1, 0x435, 0x5d0, 0x627, 0x928, 0x0b47, 0x0b3e,
];
const out = [];
const hex = (s) => cps(s).map((x) => x.toString(16)).join(' ');
for (let t = 0; t < 4000; t++) {
	const n = 1 + rnd(8);
	const arr = [];
	for (let i = 0; i < n; i++) arr.push(interesting[rnd(interesting.length)]);
	const s = String.fromCodePoint(...arr);
	out.push([s, s.normalize('NFC'), s.normalize('NFD'), s.normalize('NFKC'), s.normalize('NFKD')].map(hex).join('\t'));
}
writeFileSync(join(here, 'testdata', 'normalize_cases.txt'), `${out.join('\n')}\n`);
console.log(`${canonical.length} canonical, ${compat.length} compat, ${ccc.size} non-starters in ${rank} classes, ${pairs.length} pairs, ${pool.length} pool`);
