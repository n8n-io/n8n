// Generates xmlent.zig: the entity tables of the XML parser (xml.zig).
//
// - `sax`: the entities of sax 1.2.4 (non-strict entity set, the default of
//   xml2js 0.5), which rss-parser and n8n's XML node use.
// - `html`: entities 2.2.0 (`decodeHTML` of rss-parser's snippets), with the
//   legacy names that need no semicolon, and the code point remaps of
//   `decode_codepoint`.
//
// Run from workflow-runtime: node src/core/gen_xmlent.mjs && zig fmt src/core/xmlent.zig
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const nodesBase = join(here, '../../../packages/nodes-base/package.json');
const rss = createRequire(createRequire(nodesBase).resolve('rss-parser'));
const xml2js = createRequire(rss.resolve('xml2js'));
const sax = xml2js('sax');
const entitiesDir = dirname(rss.resolve('entities/package.json'));
const entities = rss(join(entitiesDir, 'lib/maps/entities.json'));
const legacy = rss(join(entitiesDir, 'lib/maps/legacy.json'));
const remap = rss(join(entitiesDir, 'lib/maps/decode.json'));

const str = (s) => JSON.stringify(s).replace(/\\u([0-9a-fA-F]{4})/g, (_, h) => `\\u{${h}}`);
const byName = (a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0);

const saxRows = Object.entries(sax.ENTITIES)
	.map(([k, v]) => [k, typeof v === 'number' ? String.fromCharCode(v) : v])
	.sort(byName);
const htmlRows = Object.entries(entities).sort(byName);
const legacySet = new Set(Object.keys(legacy));
const remapRows = Object.entries(remap).map(([k, v]) => [Number(k), v]).sort((a, b) => a[0] - b[0]);

let out = `//! Generated by gen_xmlent.mjs. Do not edit.\n\n`;
out += `pub const Entry = struct { name: []const u8, value: []const u8 };\n`;
out += `pub const HtmlEntry = struct { name: []const u8, value: []const u8, legacy: bool };\n\n`;
out += `/// sax 1.2.4 \`ENTITIES\`, sorted by name.\npub const sax = [_]Entry{\n`;
for (const [k, v] of saxRows) out += `    .{ .name = ${str(k)}, .value = ${str(v)} },\n`;
out += `};\n\n/// entities 2.2.0 \`entities.json\`, sorted by name; \`legacy\`: no semicolon needed.\npub const html = [_]HtmlEntry{\n`;
for (const [k, v] of htmlRows) {
	out += `    .{ .name = ${str(k)}, .value = ${str(v)}, .legacy = ${legacySet.has(k)} },\n`;
}
out += `};\n\n/// entities 2.2.0 \`decode.json\`: code points that numeric references remap.\npub const remap = [_][2]u21{\n`;
for (const [k, v] of remapRows) out += `    .{ ${k}, ${v} },\n`;
out += `};\n`;
writeFileSync(join(here, 'xmlent.zig'), out);
console.log(`sax ${saxRows.length}, html ${htmlRows.length}, remap ${remapRows.length}`);
