// Generates mime_tables.zig from the MIME table of the workflow language
// (packages/@n8n/workflow-lang/src/generated/mime-table.generated.ts, made
// from the package mime-types). Run from workflow-runtime:
//   node src/core/gen_mime.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const source = new URL(
	'../../../packages/@n8n/workflow-lang/src/generated/mime-table.generated.ts',
	import.meta.url,
);
const text = readFileSync(source, 'utf8');
const header = /^\/\/ Generated by (.*)$/m.exec(text)?.[1] ?? '';
const literal = /export const MIME_TABLE: string = ("(?:[^"\\]|\\.)*");/.exec(text)?.[1];
if (literal === undefined) throw new Error('The MIME table has another form.');
const lines = JSON.parse(literal)
	.split('\n')
	.filter((line) => line !== '');
for (const line of lines) {
	if (!/^[\x21-\x7e]+\|[\x21-\x7e]*\|(,[\x21-\x7e]*,)?$/.test(line) || line.includes('\\'))
		throw new Error(`The line "${line}" has another form.`);
}
const out = [
	'//! The MIME types of the package mime-types, one line for each type:',
	'//! `<type>|<first extension>|,<extension>,<extension>,`. A type can have no',
	'//! list. The lines keep the order of the package, so the first line that',
	'//! holds an extension gives its type, as `lookup` does.',
	`//! Generated by src/core/gen_mime.mjs (source: ${header.replace(/\.? ?Do not edit\.?$/, '')}). Do not edit.`,
	'',
	`pub const line_count = ${lines.length};`,
	'',
	'pub const table: []const u8 =',
	...lines.map((line) => `    \\\\${line}`),
	';',
	'',
];
writeFileSync(new URL('mime_tables.zig', import.meta.url), out.join('\n'));
