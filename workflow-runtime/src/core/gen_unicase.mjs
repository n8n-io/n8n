// Generates unicase.zig and testdata/unicase_cases.txt from the case mapping
// of the Node.js that runs it (ICU in V8), so the runtime's toUpperCase and
// toLowerCase give the same results as JavaScript.
//
// Run from workflow-runtime: node src/core/gen_unicase.mjs && zig fmt src/core/unicase.zig
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const MAX = 0x10ffff;
const isSurrogate = (cp) => cp >= 0xd800 && cp <= 0xdfff;
const cps = (s) => [...s].map((c) => c.codePointAt(0));

/** Single-code-point mappings as ranges, and multi-code-point mappings. */
function tables(map) {
	const singles = [];
	const multis = [];
	for (let cp = 0; cp <= MAX; cp++) {
		if (isSurrogate(cp)) continue;
		const out = cps(map(String.fromCodePoint(cp)));
		if (out.length === 1 && out[0] === cp) continue;
		if (out.length === 1) singles.push([cp, out[0] - cp]);
		else multis.push([cp, out]);
	}
	const mapped = new Set([...singles.map((s) => s[0]), ...multis.map((m) => m[0])]);
	// Runs of the same delta with stride 1, or stride 2 when the code point between has no mapping.
	const ranges = [];
	for (const [cp, delta] of singles) {
		const last = ranges[ranges.length - 1];
		if (last && last.delta === delta) {
			const gap = cp - last.hi;
			if (gap === 1 && (last.stride === 1 || last.lo === last.hi)) {
				last.hi = cp;
				last.stride = 1;
				continue;
			}
			if (gap === 2 && (last.stride === 2 || last.lo === last.hi) && !mapped.has(cp - 1)) {
				last.hi = cp;
				last.stride = 2;
				continue;
			}
		}
		ranges.push({ lo: cp, hi: cp, stride: 1, delta });
	}
	return { ranges, multis };
}

/** Ranges of the code points that match a property. */
function propertyRanges(re) {
	const out = [];
	for (let cp = 0; cp <= MAX; cp++) {
		if (!re.test(String.fromCodePoint(cp))) continue;
		const last = out[out.length - 1];
		if (last && last[1] === cp - 1) last[1] = cp;
		else out.push([cp, cp]);
	}
	return out;
}

const upper = tables((s) => s.toUpperCase());
const lower = tables((s) => s.toLowerCase());
const cased = propertyRanges(/^\p{Cased}$/u);
const ignorable = propertyRanges(/^\p{Case_Ignorable}$/u);

// ECMAScript Canonicalize (non-Unicode, ignoreCase) for each UTF-16 code unit.
const canon = new Uint16Array(0x10000);
for (let ch = 0; ch < 0x10000; ch++) {
	const u = String.fromCharCode(ch).toUpperCase();
	canon[ch] = u.length !== 1 ? ch : ch >= 128 && u.charCodeAt(0) < 128 ? ch : u.charCodeAt(0);
}
const classes = new Map();
for (let ch = 0; ch < 0x10000; ch++) {
	const list = classes.get(canon[ch]) ?? [];
	list.push(ch);
	classes.set(canon[ch], list);
}
const inverse = [...classes].filter(([, list]) => list.length > 1).sort((a, b) => a[0] - b[0]);
const maxInverse = Math.max(...inverse.map(([, l]) => l.length));

// Checksums of Node's own results, which the Zig tests recompute from the tables.
function fnv(parts) {
	let h = 0xcbf29ce484222325n;
	const prime = 0x100000001b3n;
	for (const p of parts) {
		for (const b of Buffer.from(p, 'utf8')) {
			h ^= BigInt(b);
			h = (h * prime) & 0xffffffffffffffffn;
		}
		h = (h * prime) & 0xffffffffffffffffn; // a zero byte after each part
	}
	return h;
}
const all = [];
for (let cp = 0; cp <= MAX; cp++) if (!isSurrogate(cp)) all.push(String.fromCodePoint(cp));
const sumUpper = fnv(all.map((s) => s.toUpperCase()));
const sumLower = fnv(all.map((s) => s.toLowerCase()));
let canonParts = [];
for (let ch = 0; ch < 0x10000; ch++) canonParts.push(String(canon[ch]));
const sumCanon = fnv(canonParts);

const hex = (n) => `0x${n.toString(16).toUpperCase()}`;
const rangeRows = (rs) =>
	rs.map((r) => `    .{ .lo = ${hex(r.lo)}, .hi = ${hex(r.hi)}, .stride = ${r.stride}, .delta = ${r.delta} },`).join('\n');
const multiRows = (ms) =>
	ms
		.map(([cp, out]) => `    .{ .cp = ${hex(cp)}, .len = ${out.length}, .out = .{ ${[...out, 0, 0].slice(0, 3).map(hex).join(', ')} } },`)
		.join('\n');
const pairRows = (ps) => ps.map(([a, b]) => `    .{ ${hex(a)}, ${hex(b)} },`).join('\n');
const inverseRows = inverse
	.map(([cc, list]) => `    .{ .cc = ${hex(cc)}, .len = ${list.length}, .units = .{ ${[...list, ...Array(maxInverse).fill(0)].slice(0, maxInverse).map(hex).join(', ')} } },`)
	.join('\n');

const zig = `//! Unicode case mapping, as String.prototype.toUpperCase and toLowerCase
//! of JavaScript give it (full mappings with SpecialCasing; Final_Sigma is
//! applied by the caller with \`isCased\` and \`isCaseIgnorable\`), and the
//! Canonicalize operation of ECMAScript regular expressions.
//!
//! GENERATED by gen_unicase.mjs from Node.js ${process.version} (ICU ${process.versions.icu},
//! Unicode ${process.versions.unicode}). Do not edit. Regenerate from
//! workflow-runtime with: node src/core/gen_unicase.mjs && zig fmt src/core/unicase.zig
const std = @import("std");

/// Code points lo..hi (every \`stride\`-th one from lo) map to cp + delta.
const Range = struct { lo: u21, hi: u21, stride: u2, delta: i32 };
/// A code point that maps to \`len\` code points.
const Multi = struct { cp: u21, len: u2, out: [3]u21 };
const Inverse = struct { cc: u16, len: u8, units: [max_inverse]u16 };

/// Most code units that share one canonical form.
pub const max_inverse = ${maxInverse};

/// A mapping result: one to three code points.
pub const Mapped = struct {
    len: u2,
    cps: [3]u21,

    pub fn slice(m: *const Mapped) []const u21 {
        return m.cps[0..m.len];
    }
};

const upper_ranges = [_]Range{
${rangeRows(upper.ranges)}
};

const upper_multi = [_]Multi{
${multiRows(upper.multis)}
};

const lower_ranges = [_]Range{
${rangeRows(lower.ranges)}
};

const lower_multi = [_]Multi{
${multiRows(lower.multis)}
};

const cased_ranges = [_][2]u21{
${pairRows(cased)}
};

const ignorable_ranges = [_][2]u21{
${pairRows(ignorable)}
};

const inverse_table = [_]Inverse{
${inverseRows}
};

fn lookupRange(table: []const Range, cp: u21) ?i32 {
    var lo: usize = 0;
    var hi: usize = table.len;
    while (lo < hi) {
        const mid = lo + (hi - lo) / 2;
        if (table[mid].lo <= cp) lo = mid + 1 else hi = mid;
    }
    if (lo == 0) return null;
    const r = table[lo - 1];
    if (cp > r.hi or (cp - r.lo) % @as(u21, r.stride) != 0) return null;
    return r.delta;
}

fn lookupMulti(table: []const Multi, cp: u21) ?Mapped {
    var lo: usize = 0;
    var hi: usize = table.len;
    while (lo < hi) {
        const mid = lo + (hi - lo) / 2;
        if (table[mid].cp < cp) lo = mid + 1 else hi = mid;
    }
    if (lo < table.len and table[lo].cp == cp) return .{ .len = table[lo].len, .cps = table[lo].out };
    return null;
}

fn inRanges(table: []const [2]u21, cp: u21) bool {
    var lo: usize = 0;
    var hi: usize = table.len;
    while (lo < hi) {
        const mid = lo + (hi - lo) / 2;
        if (table[mid][0] <= cp) lo = mid + 1 else hi = mid;
    }
    return lo > 0 and cp <= table[lo - 1][1];
}

fn map(ranges: []const Range, multi: []const Multi, cp: u21) Mapped {
    if (lookupMulti(multi, cp)) |m| return m;
    if (lookupRange(ranges, cp)) |d| {
        const out: u21 = @intCast(@as(i32, cp) + d);
        return .{ .len = 1, .cps = .{ out, 0, 0 } };
    }
    return .{ .len = 1, .cps = .{ cp, 0, 0 } };
}

/// The full upper-case mapping of one code point.
pub fn toUpper(cp: u21) Mapped {
    return map(&upper_ranges, &upper_multi, cp);
}

/// The full lower-case mapping of one code point, without the Final_Sigma
/// rule (U+03A3 gives U+03C3 here).
pub fn toLower(cp: u21) Mapped {
    return map(&lower_ranges, &lower_multi, cp);
}

pub fn isCased(cp: u21) bool {
    return inRanges(&cased_ranges, cp);
}

pub fn isCaseIgnorable(cp: u21) bool {
    return inRanges(&ignorable_ranges, cp);
}

/// Canonicalize of ECMAScript (RegExp, ignoreCase without unicode) for one
/// UTF-16 code unit. Surrogate units map to themselves.
pub fn canonicalize(ch: u16) u16 {
    if (ch >= 0xD800 and ch <= 0xDFFF) return ch;
    const m = toUpper(ch);
    if (m.len != 1 or m.cps[0] > 0xFFFF) return ch;
    const u: u16 = @intCast(m.cps[0]);
    if (ch >= 128 and u < 128) return ch;
    return u;
}

/// Every code unit c with canonicalize(c) == cc, in ascending order. Empty
/// when cc is not a canonical form.
pub fn canonicalizeInverse(cc: u16, out: *[max_inverse]u16) []u16 {
    var lo: usize = 0;
    var hi: usize = inverse_table.len;
    while (lo < hi) {
        const mid = lo + (hi - lo) / 2;
        if (inverse_table[mid].cc < cc) lo = mid + 1 else hi = mid;
    }
    if (lo < inverse_table.len and inverse_table[lo].cc == cc) {
        const e = inverse_table[lo];
        @memcpy(out[0..e.len], e.units[0..e.len]);
        return out[0..e.len];
    }
    if (canonicalize(cc) != cc) return out[0..0];
    out[0] = cc;
    return out[0..1];
}

/// FNV-1a checksums of Node's results over all code points (and all code
/// units for canonicalize), for the tests in lib.zig.
pub const test_sum_upper: u64 = ${hex(sumUpper)};
pub const test_sum_lower: u64 = ${hex(sumLower)};
pub const test_sum_canonicalize: u64 = ${hex(sumCanon)};
`;
writeFileSync(join(here, 'unicase.zig'), zig);

