// Generates myerr_tables.zig from the error names of mysql2
// (lib/constants/errors.js: the `code` of a server error is the name of
// its number). Run from workflow-runtime:
//   node src/core/gen_myerr.mjs
import { readdirSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const pnpm = new URL('../../../node_modules/.pnpm/', import.meta.url);
const dir = readdirSync(pnpm).find((name) => name.startsWith('mysql2@'));
if (dir === undefined) throw new Error('mysql2 is not installed.');
const require = createRequire(import.meta.url);
const errors = require(
	new URL(`${dir}/node_modules/mysql2/lib/constants/errors.js`, pnpm).pathname,
);
const rows = Object.keys(errors)
	.filter((key) => /^\d+$/.test(key))
	.map((key) => [Number(key), errors[key]])
	.sort((a, b) => a[0] - b[0]);
for (const [code, name] of rows) {
	if (code > 65535 || !/^[A-Z0-9_]+$/.test(name)) throw new Error(`The entry ${code} has another form.`);
}
const version = dir.slice('mysql2@'.length).split('_')[0];
const out = [
	'//! The names of the MySQL error numbers as mysql2 has them, in the order',
	'//! of the numbers: `codes[i]` has the name `names[i]`.',
	`//! Generated by src/core/gen_myerr.mjs (source: mysql2 ${version}, lib/constants/errors.js). Do not edit.`,
	'',
	`pub const codes = [${rows.length}]u16{`,
	...rows.map(([code]) => `    ${code},`),
	'};',
	'',
	`pub const names = [${rows.length}][]const u8{`,
	...rows.map(([, name]) => `    "${name}",`),
	'};',
	'',
];
writeFileSync(new URL('myerr_tables.zig', import.meta.url), out.join('\n'));
