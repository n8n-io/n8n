export type StudioCopy = Record<string, string>;
export function studioCopy(
	translate: (key: `printStudio.${(typeof copyKeys)[number]}`) => string,
): StudioCopy {
	return Object.fromEntries(copyKeys.map((key) => [key, translate(`printStudio.${key}`)]));
}
