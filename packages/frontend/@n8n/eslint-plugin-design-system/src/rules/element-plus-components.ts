/** `ElButtonGroup` becomes `button-group`, the folder under `element-plus/.../components/`. */
export function elementPlusComponentPath(name: string): string {
	return name
		.slice(2)
		.replace(/([a-z0-9])([A-Z])/g, '$1-$2')
		.replace(/([A-Z]+)([A-Z][a-z])/g, '$1-$2')
		.toLowerCase();
}
