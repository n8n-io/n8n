/**
 * Generates the package README and `docs/best-practices.md` from the SDK
 * prompt constants, so the docs on npm match what the n8n MCP server serves.
 *
 * Usage:
 *   pnpm generate:docs                                 # write the committed copies
 *   node dist/docs/generate-docs.js --stamp-version    # prepack: also state the package version
 */

import * as fs from 'fs';
import * as path from 'path';
import { jsonParse } from 'n8n-workflow';

import {
	bestPracticesRegistry,
	TechniqueDescription,
	type WorkflowTechniqueType,
} from '../prompts/best-practices';
import { GROUPING_GUIDANCE, getSdkReferenceContent } from '../prompts/sdk-reference';

export const PACKAGE_NAME = '@n8n/workflow-sdk';

export const README_PATH = 'README.md';

export const BEST_PRACTICES_PATH = 'docs/best-practices.md';

const PACKAGE_DIR = path.resolve(__dirname, '../..');

const SOURCE_URL = 'https://github.com/n8n-io/n8n/tree/master/packages/@n8n/workflow-sdk';

const GENERATED_NOTICE =
	'<!-- Generated from the SDK source by `pnpm generate:docs`. Do not edit this file. -->';

export interface RenderDocsOptions {
	/** Package version to state in the docs. Set when the package is packed for npm. */
	version?: string;
}

/** Kept in the README so the test can prove that the example parses and validates. */
export const QUICK_START_EXAMPLE = `import { workflow, trigger, node, expr } from '@n8n/workflow-sdk';

const start = trigger({
  type: 'n8n-nodes-base.manualTrigger',
  version: 1,
  config: { name: 'Start' },
  output: [{}],
});

const fetchPosts = node({
  type: 'n8n-nodes-base.httpRequest',
  version: 4.3,
  config: {
    name: 'Fetch Posts',
    parameters: { method: 'GET', url: 'https://api.example.com/posts' },
  },
  output: [{ id: 1, title: 'First post' }],
});

const formatTitle = node({
  type: 'n8n-nodes-base.set',
  version: 3.4,
  config: {
    name: 'Format Title',
    parameters: {
      mode: 'manual',
      includeOtherFields: true,
      assignments: {
        assignments: [
          { id: 'title', name: 'title', value: expr('{{ $json.title.toUpperCase() }}'), type: 'string' },
        ],
      },
    },
  },
  output: [{ id: 1, title: 'FIRST POST' }],
});

export default workflow('quick-start', 'Fetch and format posts')
  .add(start)
  .to(fetchPosts)
  .to(formatTitle);`;

function unpkgUrl(file: string, { version }: RenderDocsOptions): string {
	return `https://unpkg.com/${PACKAGE_NAME}${version ? `@${version}` : ''}/${file}`;
}

function renderVersionNote({ version }: RenderDocsOptions, file: string): string {
	if (!version) {
		return '**Version:** this copy is from the n8n source repository. The copy in each published npm package states the SDK version that it documents.';
	}
	return `**Version:** \`${PACKAGE_NAME}@${version}\`. For another version, open \`https://unpkg.com/${PACKAGE_NAME}@<version>/${file}\`.`;
}

export function renderReadme(options: RenderDocsOptions = {}): string {
	return `# ${PACKAGE_NAME}

${GENERATED_NOTICE}

TypeScript SDK to create n8n workflows as code. You describe a workflow with \`workflow()\`, \`trigger()\`, \`node()\` and \`.to()\`. The SDK turns the code into n8n workflow JSON and validates it.

This file is the complete SDK reference for AI agents and developers. The \`get_workflow_sdk_reference\` tool of the n8n MCP server returns the same reference. Design guidance for common workflow techniques is in [\`${BEST_PRACTICES_PATH}\`](${unpkgUrl(BEST_PRACTICES_PATH, options)}).

${renderVersionNote(options, README_PATH)} Generated from [the SDK source](${SOURCE_URL}).

## Install

\`\`\`sh
npm install ${PACKAGE_NAME}
\`\`\`

## Quick start

\`\`\`typescript
${QUICK_START_EXAMPLE}
\`\`\`

## Convert code to workflow JSON

n8n reads SDK code with an AST interpreter, not with Node.js. The interpreter accepts only the language subset in the reference below. It does not accept \`import\` declarations, so remove the import line before you parse the code. The n8n MCP server removes it for you.

\`\`\`typescript
import { parseWorkflowCodeToBuilder, validateWorkflowBuilder } from '${PACKAGE_NAME}';

// \`code\` is the workflow code without its import line.
const builder = parseWorkflowCodeToBuilder(code);
const result = validateWorkflowBuilder(builder);
if (!result.ok) {
  console.error(result.blocking);
}
const workflowJson = builder.toJSON();
\`\`\`

The CLI converts files in both directions. It uses the same interpreter, so the input file must not contain an import line. Each command writes a new file next to the input file.

\`\`\`sh
npx workflow-sdk code-to-json workflow.ts
npx workflow-sdk json-to-code workflow.json
\`\`\`

## Node parameters

This reference does not list node parameters. Get the node types and their parameters from your n8n instance, for example with the node tools of the n8n MCP server.

${getSdkReferenceContent()}

## License

You can find the license information [here](https://github.com/n8n-io/n8n/blob/master/README.md#license).
`;
}

function renderTechniqueLine(technique: WorkflowTechniqueType, description: string): string {
	const hasGuide = bestPracticesRegistry[technique] !== undefined;
	return `- \`${technique}\`: ${description}${hasGuide ? '' : ' (no detailed guide yet)'}`;
}

export function renderBestPractices(options: RenderDocsOptions = {}): string {
	const techniques = Object.entries(TechniqueDescription) as Array<[WorkflowTechniqueType, string]>;
	const guides = Object.values(bestPracticesRegistry)
		.filter((guide) => guide !== undefined)
		.map((guide) => guide.getDocumentation());

	return `# n8n workflow best practices

${GENERATED_NOTICE}

Design guidance for common workflow techniques: recommended nodes, patterns, and common pitfalls. Read the guide for each technique that a workflow uses. The \`get_workflow_best_practices\` tool of the n8n MCP server returns the same guides. The SDK reference is in the [package README](${unpkgUrl(README_PATH, options)}).

${renderVersionNote(options, BEST_PRACTICES_PATH)}

## Techniques

${techniques.map(([technique, description]) => renderTechniqueLine(technique, description)).join('\n')}

${GROUPING_GUIDANCE}

${guides.join('\n\n')}
`;
}

/** Rendered docs, keyed by their path relative to the package root. */
export function renderDocs(options: RenderDocsOptions = {}): Record<string, string> {
	return {
		[README_PATH]: renderReadme(options),
		[BEST_PRACTICES_PATH]: renderBestPractices(options),
	};
}

export function readDocs(packageDir = PACKAGE_DIR): Record<string, string> {
	return Object.fromEntries(
		[README_PATH, BEST_PRACTICES_PATH].map((file) => [
			file,
			fs.readFileSync(path.join(packageDir, file), 'utf-8'),
		]),
	);
}

function readPackageVersion(): string {
	const content = fs.readFileSync(path.join(PACKAGE_DIR, 'package.json'), 'utf-8');
	return jsonParse<{ version: string }>(content).version;
}

function main(): void {
	const version = process.argv.includes('--stamp-version') ? readPackageVersion() : undefined;

	for (const [file, content] of Object.entries(renderDocs({ version }))) {
		const filePath = path.join(PACKAGE_DIR, file);
		fs.mkdirSync(path.dirname(filePath), { recursive: true });
		fs.writeFileSync(filePath, content);
		console.log(`Wrote ${file}`);
	}
}

if (require.main === module) {
	main();
}
