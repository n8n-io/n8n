/**
 * Tool Node Validator Plugin
 *
 * Validates Tool nodes for missing parameters and naming conventions.
 */

import type { GraphNode, NodeInstance } from '../../../types/base';
import { isToolNode, TOOLS_WITHOUT_PARAMETERS } from '../../validation-helpers';
import type { ValidatorPlugin, ValidationIssue, PluginContext } from '../types';

const SNAKE_CASE_NAME = /^[a-z][a-z0-9]*(?:_[a-z0-9]+)*$/;

/** Mirror of subnode generateNodeName — detects when config.name was omitted. */
function autoGeneratedToolName(type: string): string {
	const parts = type.split('.');
	const nodeName = parts[parts.length - 1] ?? type;
	return nodeName
		.replace(/([a-z])([A-Z])/g, '$1 $2')
		.replace(/([A-Z]+)([A-Z][a-z])/g, '$1 $2')
		.replace(/^./, (str) => str.toUpperCase())
		.replace(/^Lm/, 'LM')
		.replace(/^Llm/, 'LLM')
		.replace(/OpenAi/g, 'OpenAI')
		.replace(/Api/g, 'API');
}

function toolFamilyTokens(type: string): string[] {
	const leaf = type.split('.').pop() ?? type;
	let base = leaf;
	if (/^tool[A-Z]/.test(base)) {
		base = base.slice(4);
	} else {
		base = base.replace(/Tool$/i, '');
	}
	if (base.length === 0) return [];
	const snake = base.replace(/([a-z])([A-Z])/g, '$1_$2').toLowerCase();
	const compact = base.toLowerCase();
	return [...new Set([snake, compact].filter((token) => token.length > 0))];
}

function namingIssues(node: NodeInstance<string, string, unknown>): ValidationIssue[] {
	const issues: ValidationIssue[] = [];
	const name = node.name;
	const autoName = autoGeneratedToolName(node.type);

	if (name === autoName) {
		issues.push({
			code: 'TOOL_NAME_CONVENTION',
			message:
				`'${name}' uses the auto-generated tool name from its type. Always set an explicit ` +
				'config.name with a concise snake_case action (e.g. get_email, add_labels) — not the service display name.',
			severity: 'warning',
			violationLevel: 'minor',
			nodeName: name,
			parameterPath: 'name',
		});
		return issues;
	}

	if (!SNAKE_CASE_NAME.test(name)) {
		issues.push({
			code: 'TOOL_NAME_CONVENTION',
			message:
				`'${name}' tool name should be concise snake_case (e.g. get_email, mark_as_read). ` +
				'Display names and Title Case are wrong for agent tool names.',
			severity: 'warning',
			violationLevel: 'minor',
			nodeName: name,
			parameterPath: 'name',
		});
	}

	const lower = name.toLowerCase();
	for (const family of toolFamilyTokens(node.type)) {
		if (lower.startsWith(`${family}_`)) {
			issues.push({
				code: 'TOOL_NAME_CONVENTION',
				message:
					`'${name}' prefixes the tool name with the service/family ("${family}_…"). ` +
					'Use the action only (get_email, not gmail_get_email) unless the user asked for that exact name.',
				severity: 'warning',
				violationLevel: 'minor',
				nodeName: name,
				parameterPath: 'name',
			});
			break;
		}
	}

	return issues;
}

/**
 * Validator for Tool nodes.
 *
 * Checks for:
 * - Tool nodes with missing parameters (except tools that don't require them)
 * - Tool naming conventions (explicit snake_case, no service prefix)
 */
export const toolNodeValidator: ValidatorPlugin = {
	id: 'core:tool-node',
	name: 'Tool Node Validator',
	// No nodeTypes - we check isToolNode internally
	priority: 50,

	validateNode(
		node: NodeInstance<string, string, unknown>,
		_graphNode: GraphNode,
		ctx: PluginContext,
	): ValidationIssue[] {
		const issues: ValidationIssue[] = [];

		// Only validate tool nodes
		if (!isToolNode(node.type)) {
			return issues;
		}

		issues.push(...namingIssues(node));

		// Check via nodeTypesProvider first (dynamic detection)
		const provider = ctx.validationOptions?.nodeTypesProvider;
		if (provider) {
			const nodeType = provider.getByNameAndVersion(node.type, Number(node.version));
			const properties = nodeType?.description?.properties;
			// If provider returns info and properties is empty array, skip parameter check
			if (properties !== undefined && properties.length === 0) {
				return issues;
			}
		}

		// Fallback to static list when provider not available or doesn't have info
		if (TOOLS_WITHOUT_PARAMETERS.has(node.type)) {
			return issues;
		}

		const params = node.config?.parameters;
		if (!params || Object.keys(params).length === 0) {
			issues.push({
				code: 'TOOL_NO_PARAMETERS',
				message: `'${node.name}' has no parameters set.`,
				severity: 'warning',
				nodeName: node.name,
			});
		}

		return issues;
	},
};
