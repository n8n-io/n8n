// Writes src/extensions.ts: n8n's expression extension methods as global interface
// augmentations, read from n8n-workflow's doc metadata. Re-run after a change to the extensions
// of n8n-workflow, and check workflow-data-proxy.ts for new globals to add to contexts.ts.
// The package typecheck reports a clash with lib or @types/luxon (TS2300).
import { writeFileSync } from 'node:fs';
import path from 'node:path';
// The CJS build: the ESM build trips on a named import from @n8n/tournament.
import { extendedFunctions } from 'n8n-workflow/dist/cjs/extensions/extended-functions.js';
import type { DocMetadata, Extension } from 'n8n-workflow/dist/cjs/extensions/extensions.js';
import { ExpressionExtensions } from 'n8n-workflow/dist/cjs/extensions/index.js';
import { version } from 'n8n-workflow/package.json';

type Doc = Partial<DocMetadata> & Pick<DocMetadata, 'name'>;

/** n8n attaches the doc metadata to each helper at run time. */
const helpers: Record<string, Extension> = extendedFunctions;

/** JSDoc from n8n's doc metadata, so hover and completion details carry the docs. */
const jsdoc = (method: string, doc: Doc | undefined, indent: string): string => {
	if (!doc) return '';
	const lines = [
		...(doc.description ? [doc.description] : []),
		...(doc.name !== method ? [`Alias of \`${doc.name}()\`.`] : []),
		...(doc.args ?? [])
			.filter((a) => a.description)
			.map((a) => `@param ${a.name} ${a.description}`),
		...(doc.examples ?? [])
			.slice(0, 2)
			.map((e) => `@example ${e.example}${e.evaluated ? ` // ${e.evaluated}` : ''}`),
		...(doc.docURL ? [`@see ${doc.docURL}`] : []),
	];
	if (lines.length === 0) return '';
	return `${indent}/**\n${lines.map((l) => `${indent} * ${l.replace(/\*\//g, '* /')}`).join('\n')}\n${indent} */\n`;
};

/** A value with no known shape, declared in shapes.ts. */
const LOOSE = 'N8nLooseJson';

// Doc type strings are informal; map the ones that occur to TS.
const docType = (t: string | undefined, self: string): string => {
	switch (t) {
		case undefined:
		case 'any':
			return LOOSE;
		case 'string':
		case 'number':
		case 'boolean':
		case 'object':
			return t;
		case 'Array':
			return self === 'Array' ? 'T[]' : `${LOOSE}[]`;
		case 'Object':
			return `Record<string, ${LOOSE}>`;
		case 'DateTime':
		case 'Date':
			return t;
		case 'Function':
			return `(...args: ${LOOSE}[]) => ${LOOSE}`;
		default:
			return /^[\w\s|<>,[\]]+$/.test(t) ? t.replace(/\bany\b/g, LOOSE) : LOOSE;
	}
};

// Doc metadata says `any` where the real return is the element or key type.
const RETURN_OVERRIDES: Record<string, Record<string, string>> = {
	Array: {
		first: 'T',
		last: 'T',
		randomItem: 'T',
		unique: 'T[]',
		removeDuplicates: 'T[]',
		compact: 'T[]',
	},
	Object: { keys: 'string[]', values: `${LOOSE}[]` },
};

const signature = (method: string, doc: Doc | undefined, self: string): string => {
	const args = (doc?.args ?? [])
		.map((a) => {
			const type = docType(a.type, self);
			return a.variadic ? `...${a.name}: ${type}[]` : `${a.name}${a.optional ? '?' : ''}: ${type}`;
		})
		.join(', ');
	const returnType = RETURN_OVERRIDES[self]?.[method] ?? docType(doc?.returnType, self);
	return `${method}(${args}): ${returnType};`;
};

// n8n dispatches these at runtime, but as declarations they would collide with an existing
// property: Array#length from lib, DateTime#isWeekend from @types/luxon (a getter, not a method).
const COLLIDES: Record<string, string[]> = {
	// eslint-disable-next-line id-denylist -- the name of the built-in interface
	String: ['length'],
	Array: ['length'],
	Date: ['isWeekend'],
};

const members = (typeName: string): string => {
	const map = ExpressionExtensions.find((m) => m.typeName === typeName);
	if (!map) return '';
	return Object.entries(map.functions)
		.filter(([name]) => !COLLIDES[typeName]?.includes(name))
		.map(([name, fn]) => {
			const { doc } = fn;
			return `${jsdoc(name, doc, '\t\t')}\t\t${signature(name, doc, typeName)}`;
		})
		.join('\n');
};

// $if is rewritten by an AST hook in n8n and has no runtime doc; declared by hand below.
const helperNames = Object.keys(helpers).filter((n) => n.startsWith('$'));
const functions = helperNames.map((name) => {
	const doc = helpers[name]?.doc;
	const head = jsdoc(name, doc, '\t');
	if (name === '$ifEmpty')
		return `${head}\tfunction $ifEmpty<V, E>(value: V, defaultValue: E): V | E;`;
	if (name === '$not') return `${head}\tfunction $not(value: unknown): boolean;`;
	return `${head}\tfunction ${signature(name, doc ?? { name, returnType: 'number', args: [{ name: 'numbers', type: 'number', variadic: true }] }, 'root')}`;
});

const out = `// Generated by gen-extensions.ts from n8n-workflow ${version}. Do not edit.
/* eslint-disable id-denylist -- augments the built-in String, Number, and Boolean */
import type { DateTime, DurationUnit } from 'luxon';

// Date extensions also apply to luxon DateTime (expression-extension.ts dispatches on isDateTime).
declare module 'luxon' {
	interface DateTime {
${members('Date')}
	}
}

declare global {
	interface String {
${members('String')}
	}
	interface Number {
${members('Number')}
	}
	interface Boolean {
${members('Boolean')}
	}
	interface Array<T> {
${members('Array')}
	}
	interface Object {
${members('Object')}
	}
	interface Date {
${members('Date')}
	}

	/**
	 * Returns valueIfTrue when the condition holds, else valueIfFalse.
	 * @example $if($json.age >= 18, 'adult', 'minor')
	 * @see https://docs.n8n.io/code/builtin/convenience/
	 */
	function $if<T, F = undefined>(condition: boolean, valueIfTrue: T, valueIfFalse?: F): T | F;
${functions.join('\n')}
}

export {};
`;

writeFileSync(path.join(__dirname, '../src/extensions.ts'), out);
console.log('wrote src/extensions.ts');
