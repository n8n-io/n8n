#!/usr/bin/env node

/**
 * Keeps the frontend's source-resolution mapping in one place.
 *
 * `frontend-aliases.ts` derives the mapping from the filesystem; Vite calls it directly, so its
 * alias array cannot drift. The two consumers that must hold a literal copy — the shared module
 * tsconfig base, and editor-ui's own tsconfig `paths` — are what this script writes and checks.
 *
 *   node bin/sync-frontend-aliases.mjs           # check (CI)
 *   node bin/sync-frontend-aliases.mjs --write   # rewrite the generated tsconfig base
 */

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const packageDir = path.resolve(scriptDir, '..');
const repoRoot = path.resolve(packageDir, '..', '..', '..');

const GENERATED_TSCONFIG = 'packages/@n8n/typescript-config/tsconfig.frontend-module.json';
const EDITOR_UI = 'packages/frontend/editor-ui';

// Unrecognized arguments are ignored rather than rejected: this runs as the last link of
// `lint:ci`'s `&&` chain, and pnpm forwards a caller's trailing args (CI passes `--summarize`)
// to that last command only. Rejecting them turns any forwarded turbo flag into a CI failure.
const write = process.argv.slice(2).includes('--write');

const dist = path.join(packageDir, 'dist', 'frontend-aliases.js');
let findFrontendSourcePackages, frontendSourcePaths;
try {
	({ findFrontendSourcePackages, frontendSourcePaths } = await import(dist));
} catch {
	console.error(
		`Cannot load ${path.relative(repoRoot, dist)}.\nRun: pnpm --filter @n8n/vitest-config build`,
	);
	process.exit(2);
}

/** tsconfigs are JSONC. The frontend ones only ever carry whole-line `//` comments. */
const readTsconfig = (file) =>
	JSON.parse(
		readFileSync(path.join(repoRoot, file), 'utf8')
			.split('\n')
			.filter((line) => !line.trim().startsWith('//'))
			.join('\n'),
	);

const HEADER = `// Base tsconfig for frontend module packages (\`packages/frontend/modules/*\`).
//
// GENERATED by \`pnpm --filter @n8n/vitest-config sync-frontend-aliases --write\`. Do not edit by
// hand: \`pnpm check:frontend-aliases\` fails on drift.
//
// \`paths\` lists the L0-L2 packages a module consumes from source. Module packages are absent
// from it on purpose, which stops an *accidental* cross-module import — but it is not a
// boundary: \`paths\` is additive, so once a module declares another module as a dependency,
// pnpm symlinks it and the import typechecks clean. Boundary enforcement is the ESLint rule.
//
// Modules declare their own \`include\`, \`rootDirs\` and \`types\`, and cannot inherit them: relative
// entries in those three resolve against the *consuming* config, so inheriting them from here
// would point them at this directory. \`paths\` is the exception — it anchors to the file that
// declares it, which is what lets one base serve modules at any depth.
//
// \`useUnknownInCatchVariables\` is a cost of consuming L1/L2 packages from source rather than from
// a built \`dist\`; see the comment on it below. The ambient \`.d.ts\` shims are the other half of
// that cost, and live in each module's own tsconfig for the resolution reason above.
`;

const buildTsconfig = () => {
	const paths = frontendSourcePaths({
		repoRoot,
		fromDir: path.join(repoRoot, path.dirname(GENERATED_TSCONFIG)),
	});

	const body = {
		extends: './tsconfig.frontend.json',
		compilerOptions: {
			moduleResolution: 'bundler',
			noEmit: true,
			// `@n8n/rest-api-client` sets this in its own tsconfig, and its `catch` blocks rely on
			// it. Consuming its source means the flag has to hold here too — editor-ui carries the
			// same line. It goes away when that package's source stops needing it.
			useUnknownInCatchVariables: false,
			paths,
		},
	};

	// Single-entry arrays go on one line, which is what biome formats tsconfig `paths` to — the
	// generated file has to be format-stable or `--check` and the formatter undo each other.
	const json = JSON.stringify(body, null, '\t').replace(
		/\[\n\t+("(?:[^"\\]|\\.)*")\n\t+\]/g,
		'[$1]',
	);

	return `${HEADER}${json}\n`;
};

/** Reduce a tsconfig `paths` block to one absolute src directory per package. */
const pathsByPackage = (paths, fromDir) => {
	const byPackage = new Map();

	for (const [key, [target]] of Object.entries(paths ?? {})) {
		const name = key.replace(/\/?\*$/, '');
		if (!name.startsWith('@n8n/')) continue;

		const resolved = path.resolve(fromDir, target.replace(/\/?\*$/, ''));
		byPackage.set(name, resolved.endsWith('.ts') ? path.dirname(resolved) : resolved);
	}

	return byPackage;
};

const failures = [];
const notes = [];

// 1. The generated module base must match what the scan produces.
const expected = buildTsconfig();
const actual = (() => {
	try {
		return readFileSync(path.join(repoRoot, GENERATED_TSCONFIG), 'utf8');
	} catch {
		return undefined;
	}
})();

if (write) {
	if (actual !== expected) {
		writeFileSync(path.join(repoRoot, GENERATED_TSCONFIG), expected);
		console.log(`wrote ${GENERATED_TSCONFIG}`);
	} else {
		console.log(`${GENERATED_TSCONFIG} already up to date`);
	}
} else if (actual !== expected) {
	failures.push(`${GENERATED_TSCONFIG} is out of date — run \`pnpm check:frontend-aliases:write\``);
}

// 2. editor-ui typechecks and builds from the same mapping, or the two drift apart again:
//    every package Vite resolves from source must also be pathed to source for vue-tsc.
const editorUiDir = path.join(repoRoot, EDITOR_UI);
const editorUiPaths = pathsByPackage(
	readTsconfig(`${EDITOR_UI}/tsconfig.json`).compilerOptions?.paths,
	editorUiDir,
);
const editorUiManifest = JSON.parse(readFileSync(path.join(editorUiDir, 'package.json'), 'utf8'));
const editorUiDeclares = new Set([
	...Object.keys(editorUiManifest.dependencies ?? {}),
	...Object.keys(editorUiManifest.devDependencies ?? {}),
]);

for (const pkg of findFrontendSourcePackages(repoRoot)) {
	if (!editorUiDeclares.has(pkg.name)) {
		notes.push(`${pkg.name}: not aliased for editor-ui (not a declared dependency)`);
		continue;
	}

	const pathed = editorUiPaths.get(pkg.name);
	if (!pathed) {
		failures.push(
			`${EDITOR_UI}/tsconfig.json: no \`paths\` entry for ${pkg.name}, which Vite resolves from source`,
		);
	} else if (pathed !== pkg.srcDir) {
		failures.push(
			`${EDITOR_UI}/tsconfig.json: ${pkg.name} is pathed to ${path.relative(repoRoot, pathed)}, expected ${path.relative(repoRoot, pkg.srcDir)}`,
		);
	}
}

for (const note of notes) console.log(`note: ${note}`);

if (failures.length > 0) {
	console.error(`\n${failures.length} problem(s):`);
	for (const failure of failures) console.error(`  - ${failure}`);
	process.exit(1);
}

if (!write) console.log('frontend source-resolution mapping is in sync');
