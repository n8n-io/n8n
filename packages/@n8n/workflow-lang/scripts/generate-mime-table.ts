/**
 * Writes `src/generated/mime-table.generated.ts`: the tables of the package `mime-types` that n8n uses
 * (`lookup` and `extension`), as one text. A compiled node that makes binary data holds this text.
 *
 * A line is `<type>|<first extension>|,<extension>,<extension>,`. The first extension is the result of
 * `extension(type)`. The list holds each extension for which `lookup` gives the type.
 */
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const core = createRequire(join(root, '../../core/package.json'));
const mime: { types: Record<string, string>; extensions: Record<string, string[]> } =
	core('mime-types');
const version: string = core('mime-types/package.json').version;

const owned = new Map<string, string[]>();
for (const [extension, type] of Object.entries(mime.types)) {
	owned.set(type, [...(owned.get(type) ?? []), extension]);
}
const lines: string[] = [];
for (const type of Object.keys(mime.extensions).sort()) {
	const first = mime.extensions[type][0];
	if (first === undefined) continue;
	const list = (owned.get(type) ?? []).sort();
	lines.push(`${type}|${first}|${list.length > 0 ? `,${list.join(',')},` : ''}`);
}
for (const line of lines) {
	if (/[\n\\"]/.test(line) || line.split('|').length !== 3)
		throw new Error(`The line ${line} does not fit the table format.`);
}
writeFileSync(
	join(root, 'src/generated/mime-table.generated.ts'),
	`// Generated by scripts/generate-mime-table.ts from mime-types ${version}. Do not edit.

export const MIME_TABLE: string = ${JSON.stringify(`\n${lines.join('\n')}\n`)};
`,
);
console.log(`types ${lines.length}; extensions ${Object.keys(mime.types).length}`);
