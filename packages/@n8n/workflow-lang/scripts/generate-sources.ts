/**
 * Writes `src/generated/sources.generated.ts`. It holds the SDK, prelude and node
 * library sources as strings, so the compiler needs no file system.
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

export function renderSources(): string {
	const read = (rel: string) => readFileSync(join(root, rel), 'utf8');
	const list = (dir: string) =>
		readdirSync(join(root, dir), { withFileTypes: true })
			.filter((e) => e.isFile())
			.map((e) => e.name)
			.filter((f) => f.endsWith('.ts') && !f.endsWith('.test.ts'))
			.sort()
			.map((f) => `${dir}/${f}`);
	const entries = (files: string[]) =>
		files
			.map((f) => `\t${JSON.stringify(f.replace(/^src\//, ''))}: ${JSON.stringify(read(f))},`)
			.join('\n');
	// Hand-written library nodes, then the nodes that scripts/translate-declarative.ts generates.
	const nodeFiles = [...list('src/nodes'), ...list('src/nodes/declarative')];
	// The type of each library node, so the compiler can link only the nodes a workflow names.
	const index = nodeFiles
		.map((f) => {
			const type = /^\ttype: '([^']+)',$/m.exec(read(f))?.[1];
			if (!type) throw new Error(`${f} has no node type`);
			return `\t${JSON.stringify(type)}: ${JSON.stringify(f.replace(/^src\//, ''))},`;
		})
		.join('\n');
	return [
		'// Generated by scripts/generate-sources.ts. Do not edit.',
		'',
		`export const SDK_SOURCE: string = ${JSON.stringify(read('src/sdk/index.ts'))};`,
		'',
		'export const PRELUDE_SOURCES: Record<string, string> = {',
		entries(list('src/prelude')),
		'};',
		'',
		'export const NODE_SOURCES: Record<string, string> = {',
		entries(nodeFiles),
		'};',
		'',
		'/** The file of each library node type. */',
		'export const NODE_INDEX: Record<string, string> = {',
		index,
		'};',
		'',
	].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	writeFileSync(join(root, 'src/generated/sources.generated.ts'), renderSources());
	console.log('wrote src/generated/sources.generated.ts');
}
