/**
 * Writes `src/generated/main-outputs.generated.ts`: the number of main outputs
 * of each node type of n8n-nodes-base and @n8n/nodes-langchain, when the
 * `outputs` of its description is a fixed list. A description whose `outputs`
 * is an expression depends on the parameters of the node (a Switch, a Filter),
 * so it has no entry: the converter reads those from `wholeNodeOutputs`.
 *
 * Run: `node scripts/generate-main-outputs.ts` (needs the built node packages).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const repo = join(root, '..', '..', '..');
const PACKAGES: Record<string, string> = {
	'n8n-nodes-base': join(repo, 'packages', 'nodes-base'),
	'@n8n/n8n-nodes-langchain': join(repo, 'packages', '@n8n', 'nodes-langchain'),
};

function isRecord(value: unknown): value is Record<string, unknown> {
	return typeof value === 'object' && value !== null && !Array.isArray(value);
}

/** The number of `main` entries of a fixed output list, or undefined when it is an expression. */
function mainOutputs(description: Record<string, unknown>): number | undefined {
	const outputs = description.outputs;
	if (!Array.isArray(outputs)) return undefined;
	let count = 0;
	for (const output of outputs) {
		const type = typeof output === 'string' ? output : isRecord(output) ? output.type : undefined;
		if (type === 'main') count++;
	}
	// A node without a main output has none to connect, so no count to keep.
	return count > 0 ? count : undefined;
}

/** Loads the class of a node type and gives the description of each of its versions. */
function descriptionsOf(
	pkg: string,
	name: string,
	known: Record<string, unknown>,
): Map<number, Record<string, unknown>> {
	const dir = PACKAGES[pkg];
	const entry = known[name];
	if (
		!isRecord(entry) ||
		typeof entry.sourcePath !== 'string' ||
		typeof entry.className !== 'string'
	) {
		throw new Error(`${pkg}.${name} is not in ${pkg}`);
	}
	const req = createRequire(join(dir, 'package.json'));
	const mod: unknown = req(join(dir, entry.sourcePath));
	const ctor: unknown = isRecord(mod) ? mod[entry.className] : undefined;
	if (typeof ctor !== 'function') throw new Error(`${pkg}.${name}: no class ${entry.className}`);
	const instance: unknown = Reflect.construct(ctor, []);
	const out = new Map<number, Record<string, unknown>>();
	const add = (description: unknown) => {
		if (!isRecord(description)) return;
		const v = description.version;
		const versions = Array.isArray(v) ? v : [v ?? 1];
		for (const version of versions) if (typeof version === 'number') out.set(version, description);
	};
	if (isRecord(instance) && isRecord(instance.nodeVersions)) {
		for (const [version, node] of Object.entries(instance.nodeVersions)) {
			if (!isRecord(node) || !isRecord(node.description)) continue;
			out.set(Number(version), node.description);
		}
	} else if (isRecord(instance)) {
		add(instance.description);
	}
	return out;
}

const byVersion: Record<string, number> = {};
const byType: Record<string, number> = {};
for (const [pkg, dir] of Object.entries(PACKAGES)) {
	const known: unknown = JSON.parse(readFileSync(join(dir, 'dist/known/nodes.json'), 'utf8'));
	if (!isRecord(known)) throw new Error(`${pkg}: the known node list is not an object`);
	for (const name of Object.keys(known).sort()) {
		let versions: Map<number, Record<string, unknown>>;
		try {
			versions = descriptionsOf(pkg, name, known);
		} catch (e) {
			// A node that the package cannot load here (a missing dependency) has no count.
			console.warn(`skipped ${pkg}.${name}: ${String(e)}`);
			continue;
		}
		const type = `${pkg}.${name}`;
		const counts: number[] = [];
		let fixed = true;
		for (const [version, description] of versions) {
			const count = mainOutputs(description);
			if (count === undefined) {
				fixed = false;
				continue;
			}
			byVersion[`${type}@${version}`] = count;
			counts.push(count);
		}
		// Every version must give the same static count: a type with an expression version is dynamic.
		if (fixed && counts.length > 0 && counts.every((c) => c === counts[0]))
			byType[type] = counts[0];
	}
}

writeFileSync(
	join(root, 'src/generated/main-outputs.generated.ts'),
	[
		'// Generated by scripts/generate-main-outputs.ts. Do not edit.',
		'',
		'/** The number of main outputs of each `type@version` with a fixed output list. */',
		`export const NODE_MAIN_OUTPUTS: Record<string, number> = ${JSON.stringify(byVersion)};`,
		'',
		'/** The number of main outputs of a type at any version, when every version gives the same. */',
		`export const NODE_MAIN_OUTPUTS_ANY_VERSION: Record<string, number> = ${JSON.stringify(byType)};`,
		'',
	].join('\n'),
);
console.log(
	`${Object.keys(byType).length} node types, ${Object.keys(byVersion).length} type versions`,
);
