/**
 * Audits the `inject` of every n8n credential type against what n8n v1 does
 * to the same request (spec section 7), and writes
 * `docs/credential-audit.md`.
 *
 * Run: `node scripts/credential-audit.ts` (needs the built node packages).
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import type { AuditEntry, AuditResult } from '../src/credentials/audit.ts';
import { auditAll, KNOWN_DIFFERENCES } from '../src/credentials/audit.ts';
import type { InjectKind } from '../src/credentials/inject.ts';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

const APPLIED: InjectKind[] = ['generic', 'oauth2', 'manual'];

function result(entry: AuditEntry): string {
	if (entry.differences.length > 0) return '**differs**';
	if (entry.skipped) return 'not compared';
	return 'same';
}

function notes(entry: AuditEntry): string {
	if (entry.differences.length > 0) {
		const from = entry.variant ? ` (data: ${entry.variant})` : '';
		const reason = KNOWN_DIFFERENCES[entry.type] ?? entry.reasons.join('; ');
		const prefix = reason === '' ? '' : `${reason} — `;
		return `${prefix}${entry.differences.join('; ')}${from}`;
	}
	return entry.skipped ?? entry.reasons.join('; ');
}

function row(entry: AuditEntry): string {
	const cells = [entry.type, entry.kind, result(entry), notes(entry)];
	return `| ${cells.map((cell) => cell.replaceAll('|', '\\|')).join(' | ')} |`;
}

function table(entries: AuditEntry[]): string[] {
	const lines = ['| Credential type | Inject kind | Result | Notes |', '| --- | --- | --- | --- |'];
	for (const entry of entries) lines.push(row(entry));
	return lines;
}

function count(entries: AuditEntry[], predicate: (entry: AuditEntry) => boolean): number {
	return entries.filter(predicate).length;
}

function render(audit: AuditResult): string {
	const { entries, appliedDiffs, fallbackDiffs, failures } = audit;
	const applied = entries.filter((entry) => APPLIED.includes(entry.kind));
	const fallbackDiffers = new Set(fallbackDiffs.map((entry) => entry.type));
	const other = entries.filter(
		(entry) => !APPLIED.includes(entry.kind) && !fallbackDiffers.has(entry.type),
	);
	const lines: string[] = [];
	const emit = (line = '') => lines.push(line);
	emit('# Credential inject audit');
	emit();
	emit('Generated by `scripts/credential-audit.ts`. Do not edit.');
	emit();
	emit(
		'The credentials tool writes an `inject` rule for each credential type that the compiled node library runs in the runtime (spec section 7). This audit compares that rule with n8n v1: it gives both sides the same request, `GET https://example.test/x` with no headers and no query, and three credential data sets (`defaults`, `filled` and `toggled`, which come from the properties of the type). For the v1 side it runs the real `authenticate` of the n8n credential type, or applies a generic `authenticate` as n8n-core does. For the inject side it applies the rule as the runtime does: `headers`, `defaultHeaders`, `qs`, `basicAuth` and the fields of `body`.',
	);
	emit();
	emit(
		'`same` means that both sides set the same header names (ignoring case), the same header values, the same query parameters and the same body fields. `not compared` gives the reason.',
	);
	emit();
	emit('## Summary');
	emit();
	emit(`* Credential types loaded: ${entries.length}`);
	emit(`* The runtime applies the inject for ${applied.length} of them (${APPLIED.join(', ')})`);
	emit(`* The runtime applies the inject and the rule differs: ${appliedDiffs.length}`);
	emit(
		`* Of those, ${count(appliedDiffs, (e) => KNOWN_DIFFERENCES[e.type] !== undefined)} stay different, with the reason in the table`,
	);
	emit(`* The node goes to the fallback host and the rule differs: ${fallbackDiffs.length}`);
	const notComparedOther = count(other, (e) => e.skipped !== undefined);
	const notComparedApplied = count(
		applied,
		(e) => e.differences.length === 0 && e.skipped !== undefined,
	);
	emit(
		`* Not compared: ${notComparedApplied} of the applied kinds, and ${notComparedOther} of the other kinds`,
	);
	if (failures.length > 0) emit(`* Credential types that did not load: ${failures.length}`);
	emit();
	emit('## Types that the runtime applies');
	emit();
	emit(
		'These types derive a `generic`, `oauth2` or `manual` inject. A `differs` row is a defect in the rule, unless the note gives a limit of the inject format.',
	);
	emit();
	lines.push(...table(applied));
	emit();
	if (fallbackDiffs.length > 0) {
		emit('## Types that differ and that the runtime does not apply');
		emit();
		emit(
			'`deriveInject` does not convert these types, so the compiled node library sends the node to the fallback host, which applies the credential as v1 does. The rule never reaches a native request, so these rows are not defects. Many of them are simple headers that the inject format could hold; converting one changes the routing of every node that uses the type (`NOT_INJECTABLE`), so the audit lists them for a separate step.',
		);
		emit();
		lines.push(...table(fallbackDiffs));
		emit();
	}
	emit('## Other types');
	emit();
	emit(
		'These types have no `authenticate` (the node code applies the credential) or the tool cannot convert them.',
	);
	emit();
	lines.push(...table(other));
	emit();
	if (failures.length > 0) {
		emit('## Types that did not load');
		emit();
		for (const failure of failures) emit(`* ${failure.name}: ${failure.error}`);
		emit();
	}
	return `${lines.join('\n')}\n`;
}

const audit = await auditAll();
const doc = render(audit);
writeFileSync(join(root, 'docs/credential-audit.md'), doc);

const applied = audit.entries.filter((entry) => APPLIED.includes(entry.kind));
process.stdout.write(`credential types: ${audit.entries.length}\n`);
process.stdout.write(`the runtime applies ${applied.length}\n`);
process.stdout.write(`differ, applied: ${audit.appliedDiffs.length}\n`);
process.stdout.write(`differ, fallback host: ${audit.fallbackDiffs.length}\n`);
for (const entry of audit.appliedDiffs) {
	const known = KNOWN_DIFFERENCES[entry.type] === undefined ? '' : ' [known]';
	process.stdout.write(`  ${entry.type} (${entry.kind})${known}: ${notes(entry)}\n`);
}
