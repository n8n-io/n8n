/**
 * Measures how many n8n credential types the credentials tool converts to an
 * `inject` (spec section 7), and writes `docs/credential-coverage.md` and
 * `src/credentials/not-injectable.generated.ts` (the types that the converter
 * sends to the fallback host).
 *
 * Run: `node scripts/credential-coverage.ts` (needs the built node packages).
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import type { InjectKind } from '../src/credentials/inject.ts';
import { deriveInject } from '../src/credentials/inject.ts';
import { loadCredentialTypes, registryOf } from '../src/credentials/types.ts';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const { types, failures } = loadCredentialTypes();
const registry = registryOf(types);

const byKind = new Map<InjectKind, string[]>();
const reasons = new Map<string, string[]>();
const bySource = new Map<string, number>();
for (const type of registry.names()) {
	const result = deriveInject(registry, type);
	byKind.set(result.kind, [...(byKind.get(result.kind) ?? []), type]);
	const source = registry.get(type)?.source ?? '?';
	bySource.set(source, (bySource.get(source) ?? 0) + 1);
	if (result.kind === 'unsupported') {
		// Group by the kind of reason, not by the field name. Count a type once per reason.
		const keys = new Set(
			result.reasons.map((reason) =>
				reason
					.replace(/^.*?: /, '')
					.replace(
						/^the expression .* is not a credential field$/s,
						'complex expression (a condition, a function call or another operator)',
					),
			),
		);
		for (const key of keys) reasons.set(key, [...(reasons.get(key) ?? []), type]);
	}
}

const total = types.length;
const count = (kind: InjectKind) => byKind.get(kind)?.length ?? 0;
const pct = (n: number) => `${((100 * n) / total).toFixed(1)}%`;
const converted = count('generic') + count('oauth2') + count('manual');
const withAuth = total - count('none');

const lines: string[] = [];
const emit = (line = '') => lines.push(line);
emit('# Credential coverage');
emit();
emit('Generated by `scripts/credential-coverage.ts`. Do not edit.');
emit();
emit(
	'The `wfc credentials` command derives the `inject` of a credentials file entry (spec section 7) from the `authenticate` property of the n8n credential type. This file counts the credential types of the built node packages.',
);
emit();
emit(`Packages: ${[...bySource].map(([s, n]) => `\`${s}\` (${n})`).join(', ')}.`);
if (failures.length > 0) {
	emit();
	emit(`Types that failed to load: ${failures.map((f) => `\`${f.name}\``).join(', ')}.`);
}
emit();
emit('| Result | Types | Share |');
emit('|---|---|---|');
emit(`| Converted: generic \`authenticate\` | ${count('generic')} | ${pct(count('generic'))} |`);
emit(
	`| Converted: OAuth2 bearer token (extends \`oAuth2Api\`) | ${count('oauth2')} | ${pct(count('oauth2'))} |`,
);
emit(`| Converted: hand-written rule | ${count('manual')} | ${pct(count('manual'))} |`);
emit(`| **Converted, total** | **${converted}** | **${pct(converted)}** |`);
emit(`| Not convertible | ${count('unsupported')} | ${pct(count('unsupported'))} |`);
emit(
	`| No \`authenticate\`: the node code applies the credential | ${count('none')} | ${pct(count('none'))} |`,
);
emit(`| **Total** | **${total}** | |`);
emit();
emit(
	`Of the ${withAuth} types that declare how to sign a request (an \`authenticate\` property, OAuth2, or a hand-written rule), the tool converts ${converted} (${((100 * converted) / withAuth).toFixed(1)}%).`,
);
emit();
emit('Notes:');
emit();
emit('- OAuth2 types use the stored access token. The runtime does not refresh it.');
emit(
	'- A type with no `authenticate` still gets an entry with its `data`. The fallback host gives the data to v1 nodes. A compiled library node can read the data through URL or body templates (for example Telegram).',
);
emit(
	'- Templated header and query parameter names (for example `httpHeaderAuth`) are filled from the credential data when the tool builds the file.',
);
emit();
emit('## Reasons a type is not convertible');
emit();
emit('| Reason | Types | Examples |');
emit('|---|---|---|');
for (const [reason, list] of [...reasons].sort((a, b) => b[1].length - a[1].length)) {
	const examples = list
		.slice(0, 5)
		.map((t) => `\`${t}\``)
		.join(', ');
	emit(`| ${reason.replace(/\|/g, '\\|')} | ${list.length} | ${examples} |`);
}
emit();
emit('## Hand-written rules');
emit();
emit((byKind.get('manual') ?? []).map((t) => `\`${t}\``).join(', ') || 'None.');
emit();

writeFileSync(join(root, 'docs/credential-coverage.md'), `${lines.join('\n')}`);
writeFileSync(
	join(root, 'src/credentials/not-injectable.generated.ts'),
	[
		'// Generated by scripts/credential-coverage.ts. Do not edit.',
		'/** Credential types that the runtime cannot apply (`deriveInject` gives `unsupported`). */',
		'export const NOT_INJECTABLE: ReadonlySet<string> = new Set([',
		...(byKind.get('unsupported') ?? []).map((t) => `\t'${t}',`),
		']);',
		'',
	].join('\n'),
);
console.log(
	`credential types: ${total}; converted ${converted}; unsupported ${count('unsupported')}; none ${count('none')}`,
);
