import type { AppDescribedBinding, AppJsonSchema } from '@n8n/api-types';

const MAX_DEPTH = 8;

function isSchema(value: unknown): value is AppJsonSchema {
	return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function quote(key: string) {
	return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(key) ? key : JSON.stringify(key);
}

function primitiveType(type: unknown): string | null {
	switch (type) {
		case 'string':
			return 'string';
		case 'number':
		case 'integer':
			return 'number';
		case 'boolean':
			return 'boolean';
		case 'null':
			return 'null';
		default:
			return null;
	}
}

/** Converts the JSON Schema subset that the bindings describe into a TypeScript type. */
export function jsonSchemaToTs(schema: unknown, depth = 0): string {
	if (!isSchema(schema) || depth > MAX_DEPTH) return 'unknown';

	if (Array.isArray(schema.enum)) {
		return schema.enum.map((value) => JSON.stringify(value)).join(' | ') || 'never';
	}

	if (Array.isArray(schema.type)) {
		return schema.type
			.map((type: unknown) => jsonSchemaToTs({ ...schema, type }, depth))
			.join(' | ');
	}

	const primitive = primitiveType(schema.type);
	if (primitive) return primitive;

	if (schema.type === 'array') {
		return `Array<${jsonSchemaToTs(schema.items, depth + 1)}>`;
	}

	if (schema.type === 'object' || isSchema(schema.properties)) {
		const properties = isSchema(schema.properties) ? schema.properties : {};
		const required = new Set(
			Array.isArray(schema.required)
				? schema.required.filter((key): key is string => typeof key === 'string')
				: [],
		);
		const fields = Object.entries(properties).map(
			([key, value]) =>
				`${quote(key)}${required.has(key) ? '' : '?'}: ${jsonSchemaToTs(value, depth + 1)}`,
		);
		if (schema.additionalProperties !== false) fields.push('[key: string]: unknown');
		return fields.length === 0 ? 'Record<string, never>' : `{ ${fields.join('; ')} }`;
	}

	return 'unknown';
}

/**
 * Renders `src/n8n-bindings.d.ts` for an app. The file augments the `Bindings`
 * interface of `@n8n/app-sdk`, so binding keys and payloads are type-checked.
 * Missing bindings are left out.
 */
export function renderBindingTypes(bindings: AppDescribedBinding[]): string {
	const workflows: string[] = [];
	const tables: string[] = [];
	const agents: string[] = [];

	for (const binding of bindings) {
		if (binding.missing) continue;
		const key = quote(binding.key);
		if (binding.kind === 'workflow') {
			workflows.push(
				`${key}: { input: ${jsonSchemaToTs(binding.input)}; output: ${jsonSchemaToTs(binding.output)} };`,
			);
		} else if (binding.kind === 'dataTable') {
			tables.push(
				`${key}: { row: ${jsonSchemaToTs(binding.row)}; permissions: ${JSON.stringify(binding.permissions)} };`,
			);
		} else {
			agents.push(`${key}: { permissions: ${JSON.stringify(binding.permissions)} };`);
		}
	}

	const section = (name: string, lines: string[]) =>
		[`\t\t${name}: {`, ...lines.map((line) => `\t\t\t${line}`), '\t\t};'].join('\n');

	return [
		'// Generated by n8n from the app bindings. Do not edit.',
		"import '@n8n/app-sdk';",
		'',
		"declare module '@n8n/app-sdk' {",
		'\tinterface Bindings {',
		section('workflows', workflows),
		section('tables', tables),
		section('agents', agents),
		'\t}',
		'}',
		'',
	].join('\n');
}
