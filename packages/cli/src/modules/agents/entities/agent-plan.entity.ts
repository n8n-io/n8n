import { DateTimeColumn, JsonColumn, WithTimestamps } from '@n8n/db';
import {
	Check,
	Column,
	Entity,
	Index,
	JoinColumn,
	ManyToOne,
	PrimaryColumn,
	type Relation,
} from '@n8n/typeorm';
import type { JsonObject } from 'n8n-workflow';

import type { AgentExecutionThread } from './agent-execution-thread.entity';

@Entity({ name: 'agent_plan' })
@Index(['threadId'])
@Index(['threadId'], { unique: true, where: '"closedAt" IS NULL' })
@Check('"revision" > 0')
@Check('"formatVersion" > 0')
export class AgentPlan extends WithTimestamps {
	@PrimaryColumn({ type: 'uuid', comment: 'Plan ID generated by the caller' })
	id: string;

	@Column({ type: 'varchar', length: 128, comment: 'Session that owns the plan' })
	threadId: string;

	@ManyToOne('AgentExecutionThread', { onDelete: 'CASCADE' })
	@JoinColumn({ name: 'threadId' })
	thread: Relation<AgentExecutionThread>;

	@Column({ type: 'int', default: 1, comment: 'Current document revision' })
	revision: number;

	@Column({ type: 'int', comment: 'Version of the plan JSON format' })
	formatVersion: number;

	@JsonColumn({ comment: 'Opaque plan document' })
	data: JsonObject;

	@DateTimeColumn({ precision: 3, nullable: true, comment: 'NULL while the plan is active' })
	closedAt: Date | null;
}
