/**
 * API-42 spike: generate a type-safe internal API client for the frontend.
 *
 * RUNTIME approach (same source of truth Express uses): side-effect require the
 * compiled controllers so their decorators populate `ControllerRegistryMetadata`,
 * then read it. This survives any new way of defining a controller — as long as
 * it registers a route, the generator sees it (unlike static source parsing).
 *
 * Request DTOs come from `reflect-metadata` (`design:paramtypes`), read off the
 * prototype so no controller is instantiated (no DI graph, no DB). Response DTOs
 * come from `@ApiResponse` (`route.responseDto`). Only routes that declare a
 * response DTO are emitted.
 *
 * Reads the COMPILED output, so it must run after `tsc` (it is wired into
 * `scripts/build.mjs`, which runs after the TypeScript build).
 */
require('reflect-metadata');
const fs = require('node:fs');
const path = require('node:path');
const glob = require('fast-glob');

const CLI_ROOT = path.resolve(__dirname, '..');
const REPO = path.resolve(CLI_ROOT, '../..');
const DIST = path.join(CLI_ROOT, 'dist');
const OUT = path.join(
	REPO,
	'packages/frontend/@n8n/rest-api-client/src/generated/internal-api-client.ts',
);

// 1. Populate the registry: require every compiled controller for its side effect.
const controllerFiles = glob
	.sync('**/*.controller.js', { cwd: DIST, absolute: true })
	// public-api is a separate surface; e2e.controller `process.exit()`s at import
	// time outside E2E tests, so it can't be required standalone.
	.filter((f) => !f.includes('/public-api/') && !f.endsWith('e2e.controller.js'));

const skipped = [];
for (const file of controllerFiles) {
	try {
		require(file);
	} catch (error) {
		// A controller that can't be required standalone (heavy import-time side
		// effect) is skipped — its routes just won't be in the generated client.
		skipped.push({ file: path.relative(DIST, file), message: String(error && error.message) });
	}
}

// 2. Read the registry (same singleton the controllers just registered into).
const { Container } = require('@n8n/di');
const { ControllerRegistryMetadata } = require('@n8n/decorators');
const metadata = Container.get(ControllerRegistryMetadata);

// Namespace per controller so handler names can't collide: '/otel' -> 'otel'.
function nsFromBasePath(bp) {
	return bp
		.replace(/^\/+/, '')
		.replace(/\//g, '-')
		.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
}

const routes = [];
const dtoNames = new Set();

for (const ControllerClass of metadata.controllerClasses) {
	const cMeta = metadata.getControllerMetadata(ControllerClass);
	if (cMeta.isPublicApi) continue;
	const ns = nsFromBasePath(cMeta.basePath);

	for (const [handlerName, route] of cMeta.routes) {
		if (!route.responseDto) continue; // only endpoints with a declared response

		const paramTypes =
			Reflect.getMetadata('design:paramtypes', ControllerClass.prototype, handlerName) || [];
		let body, query;
		route.args.forEach((arg, i) => {
			if (!arg) return;
			if (arg.type === 'body') body = paramTypes[i] && paramTypes[i].name;
			else if (arg.type === 'query') query = paramTypes[i] && paramTypes[i].name;
		});

		const responseDto = route.responseDto.name;
		const sub = route.path === '/' ? '' : route.path;

		[body, query, responseDto].forEach((n) => n && dtoNames.add(n));
		routes.push({
			ns,
			name: handlerName,
			httpMethod: route.method.toUpperCase(),
			path: cMeta.basePath + sub,
			body,
			query,
			responseDto,
		});
	}
}

// 3. Emit — one contract per controller namespace + a composing factory.
const byNs = new Map();
for (const r of routes) {
	if (!byNs.has(r.ns)) byNs.set(r.ns, []);
	byNs.get(r.ns).push(r);
}
const namespaces = [...byNs.keys()].sort();

const lines = [];
lines.push('// AUTO-GENERATED by scripts/generate-internal-api-client.cjs — DO NOT EDIT.');
lines.push('/* eslint-disable */');
lines.push(`import { ${[...dtoNames].sort().join(', ')} } from '@n8n/api-types';`);
lines.push("import type { z } from 'zod';");
lines.push('');
lines.push("import type { IRestApiContext } from '../types';");
lines.push("import { createTypedClient, defineContract, responseType } from '../typed-client';");
lines.push('');
for (const ns of namespaces) {
	lines.push(`const ${ns}Contract = defineContract({`);
	for (const r of byNs.get(ns).sort((a, b) => a.name.localeCompare(b.name))) {
		const parts = [`method: '${r.httpMethod}'`, `path: '${r.path}'`];
		if (r.body) parts.push(`body: ${r.body}`);
		if (r.query) parts.push(`query: ${r.query}`);
		// Type comes from the response DTO; runtime validation happens on the backend
		// (via @ApiResponse), so the client stays a pure type layer with no parse throw.
		if (r.responseDto) parts.push(`response: responseType<z.infer<typeof ${r.responseDto}.schema>>()`);
		lines.push(`\t${r.name}: { ${parts.join(', ')} },`);
	}
	lines.push('});');
	lines.push('');
}
lines.push('export const createInternalApiClient = (ctx: IRestApiContext) => ({');
for (const ns of namespaces) {
	lines.push(`\t${ns}: createTypedClient(ctx, ${ns}Contract),`);
}
lines.push('});');
lines.push('');

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, lines.join('\n'));

console.log(`[internal-api-client] wrote ${path.relative(REPO, OUT)} (${routes.length} routes)`);
for (const ns of namespaces) {
	for (const r of byNs.get(ns)) console.log(`  ${r.ns}.${r.name}  ${r.httpMethod} ${r.path} -> ${r.responseDto}`);
}
if (skipped.length) console.log(`  (skipped ${skipped.length} controller file(s) that could not be required)`);
